// "Say hello in Python": a real Python REPL in the browser (Pyodide).
// It loads only when the visitor presses Start, then imports the SAME suzani
// module that the Django server uses, so draw("Name") matches the printed badge.
(() => {
  const root = document.querySelector("[data-terminal]");
  if (!root) return;
  const PYODIDE = "https://cdn.jsdelivr.net/pyodide/v0.27.2/full/";
  const log = root.querySelector("[data-log]");
  const canvas = root.querySelector("[data-canvas]");
  const form = root.querySelector("[data-form]");
  const input = form.querySelector("input");
  const start = root.querySelector("[data-start]");
  const history = [];
  let hIndex = 0;
  let py = null;

  function print(text, cls) {
    const pre = document.createElement("pre");
    if (cls) pre.className = cls;
    pre.textContent = text;
    log.append(pre);
    log.scrollTop = log.scrollHeight;
  }

  function loadScript(src) {
    return new Promise((resolve, reject) => {
      const s = document.createElement("script");
      s.src = src; s.onload = resolve; s.onerror = reject;
      document.head.append(s);
    });
  }

  const PRELUDE = `
import sys, types, js
from pyodide.ffi import to_js
sys.modules["suzani"] = suzani_mod = types.ModuleType("suzani")
exec(SUZANI_SOURCE, suzani_mod.__dict__)
from suzani import rosette_svg

pycon_tj = types.ModuleType("pycon_tj")
pycon_tj.when = lambda: "12 December 2026, Dushanbe"
pycon_tj.where = lambda: "Dushanbe Innovation Institute"
pycon_tj.ticket = lambda: (js.window.location.assign("/tickets/"), "Opening tickets...")[1]
sys.modules["pycon_tj"] = pycon_tj

def draw(name="PyCon Tajikistan"):
    """Weave a suzani rosette from any text."""
    js.window.__drawSuzani(rosette_svg(str(name), size=320))
    return f"Your suzani, {name}. Same pattern as your badge."

ZEN_TJ = "Зебо беҳтар аз зишт аст.\\nОшкор беҳтар аз пинҳон аст.\\nОддӣ беҳтар аз мураккаб аст."
`;

  window.__drawSuzani = (svg) => {
    canvas.innerHTML = svg; // generated by our own Python module from numbers only
  };

  async function boot() {
    start.disabled = true;
    start.textContent = "…";
    print("Loading Python…");
    try {
      await loadScript(`${PYODIDE}pyodide.js`);
      py = await window.loadPyodide({ indexURL: PYODIDE });
      const source = await fetch(root.dataset.source).then((r) => r.text());
      py.globals.set("SUZANI_SOURCE", source);
      await py.runPythonAsync(PRELUDE);
      print(`Python ${py.runPython("import sys; sys.version.split()[0]")} is ready. Try: draw("Your name"), pycon_tj.where(), import this`);
      input.disabled = false;
      input.focus();
      start.remove();
    } catch (err) {
      print("Python could not load. Check your connection and try again.", "err");
      start.disabled = false;
      start.textContent = "Retry";
    }
  }

  async function run(code) {
    print(`>>> ${code}`);
    history.push(code); hIndex = history.length;
    if (code.trim() === "import this") {
      print(py.globals.get("ZEN_TJ"));
    }
    try {
      py.runPython("import io, sys; sys.stdout = io.StringIO(); sys.stderr = sys.stdout");
      let result;
      try {
        result = await py.runPythonAsync(`eval(compile(${JSON.stringify(code)}, "<input>", "eval"))`);
      } catch (e) {
        if (!String(e).includes("SyntaxError")) throw e;
        await py.runPythonAsync(code);
      }
      const out = py.runPython("sys.stdout.getvalue()");
      if (out) print(out.replace(/\n$/, ""));
      if (result !== undefined && result !== null) print(py.runPython("repr")(result));
    } catch (err) {
      const msg = String(err.message || err).trim().split("\n").slice(-1)[0];
      print(msg, "err");
    }
  }

  start.addEventListener("click", boot);
  form.addEventListener("submit", (e) => {
    e.preventDefault();
    const code = input.value.trim();
    if (!code || !py) return;
    input.value = "";
    run(code);
  });
  input.addEventListener("keydown", (e) => {
    if (e.key === "ArrowUp" && hIndex > 0) { input.value = history[--hIndex]; e.preventDefault(); }
    if (e.key === "ArrowDown" && hIndex < history.length) { input.value = history[++hIndex] ?? ""; e.preventDefault(); }
  });
})();
